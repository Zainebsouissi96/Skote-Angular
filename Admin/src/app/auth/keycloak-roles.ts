export const RH_ROLES = {
  EMPLOYE: 'EMPLOYE',
  CHEF_HIERARCHIQUE: 'CHEF_HIERARCHIQUE',
  RH: 'RH',
  ADMIN: 'ADMIN'
} as const;

export type RhRole = typeof RH_ROLES[keyof typeof RH_ROLES];

export const ALL_RH_ROLES: RhRole[] = [
  RH_ROLES.EMPLOYE,
  RH_ROLES.CHEF_HIERARCHIQUE,
  RH_ROLES.RH,
  RH_ROLES.ADMIN
];

